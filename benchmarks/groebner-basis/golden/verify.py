#!/usr/bin/env python3
"""groebner-basis verifier — the four mathematical invariants.

Reads `{input, candidate, id, expected?}` JSON on stdin, writes
`{pass, reason, checks}` JSON on stdout, exits 0 on PASS, 1 on FAIL.

# The invariants

This verifier implements the four-invariant Buchberger correctness
certificate (CLO Ch.2 §6 Theorem 6 p.85; tstournament problem-08 §"Invariants
the verifier checks"):

  1. shape — the candidate is well-formed (kind ∈ {ok, tagged}; if ok,
     basis is a list of expression strings, order ∈ {lex, degrevlex},
     vars matches input; if tagged, the tag is in the
     `groebner-basis/<class>` namespace).

  2. ideal_containment_input_to_candidate — every input polynomial is
     in the ideal generated by the candidate basis. Tested via SymPy's
     `reduced(input_poly, candidate_basis, ...)`: the remainder must be
     zero. If this check fails, the candidate generates a SUBSET of the
     input ideal — the candidate is missing polynomials.

  3. ideal_containment_candidate_to_input — every candidate polynomial
     is in the ideal generated by the input. Tested by computing a
     trustworthy GB of the input via `sp.groebner(input_polys, ...)`,
     then `reduced(candidate_poly, input_GB, ...)` per element. If this
     fails, the candidate has a SPURIOUS polynomial — something not in
     <F>.

     Together (2) and (3) prove ideal equality: <input> = <candidate>.

  4. s_pair_reduces_to_zero — for every pair (g_i, g_j) in the candidate
     basis, the S-polynomial S(g_i, g_j) = (lcm/LM(g_i))·g_i −
     (lcm/LM(g_j))·g_j reduces to zero modulo the candidate. By
     Buchberger's theorem (CLO Ch.2 §6 Theorem 6), this IS the Gröbner
     basis property — a basis G is a GB iff every S-pair reduces to 0
     mod G.

     The all-pairs check is the canonical certificate. For bench
     performance, a basis with > 20 elements falls back to a
     deterministic random sample of 50 pairs (seeded RNG keyed on the
     case id, so the sample is reproducible). We record the choice in
     the check's detail field.

# Refusal envelope

Per ADR-0019 §3 and the bench's PROMPT.md, the four refusal classes
are:

  groebner-basis/empty-input    polys is empty
  groebner-basis/empty-vars     vars is empty
  groebner-basis/parametric     a polynomial mentions a symbol outside vars
  groebner-basis/non-polynomial a polynomial uses a non-arithmetic head

For tagged-lane cases, the verifier checks:
  - candidate.kind == "tagged"
  - candidate.tag matches expected.tag (when expected is supplied)
  - candidate.tag starts with "groebner-basis/" and is one of the four
    declared classes

# Tolerance regime

NONE. All arithmetic is exact rational (BigInt via SymPy's QQ domain).
A candidate that is "almost a Gröbner basis" within float tolerance is
wrong.

# Wall-clock metric

`wall_clock_seconds` is recorded in the result envelope but is NEVER an
invariant. Per ADR-0036 (measurement-not-invariant pin), runtime drift
is a corpus-query metric; the per-case PASS/FAIL gate is the four
invariants alone.
"""
from __future__ import annotations

import hashlib
import json
import random
import sys
import time
from typing import Any, Dict, List, Tuple

import sympy as sp


VALID_REFUSAL_CLASSES = (
    "groebner-basis/empty-input",
    "groebner-basis/empty-vars",
    "groebner-basis/parametric",
    "groebner-basis/non-polynomial",
)


# Sample-cap for the s_pair check on large bases (>20 elements).
LARGE_BASIS_THRESHOLD = 20
SAMPLE_PAIR_COUNT = 50


# ---------------------------------------------------------------------
# Top-level dispatch
# ---------------------------------------------------------------------


def verify(case: Dict[str, Any]) -> Dict[str, Any]:
    """Run all applicable checks on a single case envelope."""
    inp = case["input"]
    cand = case["candidate"]
    expected = case.get("expected", {})
    case_id = case.get("id", "")

    checks: Dict[str, Dict[str, Any]] = {}
    t0 = time.time()

    cand_kind = cand.get("kind")
    expected_kind = expected.get("kind") if isinstance(expected, dict) else None

    # Lied-about-scope shape failure: candidate claims one kind, expected
    # demanded another.
    if expected_kind and cand_kind != expected_kind:
        checks["shape"] = {
            "pass": False,
            "detail": f"candidate.kind={cand_kind!r} but expected.kind={expected_kind!r}",
        }
        for k in (
            "ideal_containment_input_to_candidate",
            "ideal_containment_candidate_to_input",
            "s_pair_reduces_to_zero",
            "tag_matches",
        ):
            checks[k] = {"pass": False, "detail": "skipped: shape failed at kind mismatch"}
        return _aggregate(checks, t0)

    # Tagged refusal lane.
    if cand_kind == "tagged":
        checks["shape"] = _check_shape_tagged(cand)
        checks["tag_matches"] = _check_tag_matches(cand, expected)
        for k in (
            "ideal_containment_input_to_candidate",
            "ideal_containment_candidate_to_input",
            "s_pair_reduces_to_zero",
        ):
            checks[k] = {"pass": True, "detail": "n/a for kind=tagged"}
        return _aggregate(checks, t0)

    # Happy-path lane.
    shape_check = _check_shape_ok(inp, cand)
    checks["shape"] = shape_check
    if not shape_check["pass"]:
        for k in (
            "ideal_containment_input_to_candidate",
            "ideal_containment_candidate_to_input",
            "s_pair_reduces_to_zero",
        ):
            checks[k] = {"pass": False, "detail": "skipped: shape failed"}
        checks["tag_matches"] = {"pass": True, "detail": "n/a for kind=ok"}
        return _aggregate(checks, t0)

    # Parse polynomials. We work in `sympy.polys.rings` because the high-level
    # `sp.reduced()` / `sp.Poly()` API in SymPy 1.12 raises
    # NotImplementedError on the `order=` keyword — the only place a non-lex
    # multivariate order propagates correctly is the rings module's PolyElement.
    vars_ = inp["vars"]
    order = inp["order"]
    sympy_order = "grevlex" if order == "degrevlex" else order
    sym_objs = [sp.Symbol(v) for v in vars_]
    sym_locals = {v: s for v, s in zip(vars_, sym_objs)}

    # ring() returns (R, *gens) — a flat tuple
    ring_result = sp.polys.rings.ring(" ".join(vars_), sp.QQ, sympy_order)
    R = ring_result[0]

    try:
        input_exprs = [sp.sympify(p, locals=sym_locals) for p in inp["polys"]]
        cand_exprs = [sp.sympify(p, locals=sym_locals) for p in cand["basis"]]
        input_ring = [R.from_expr(e) for e in input_exprs]
        cand_ring = [R.from_expr(e) for e in cand_exprs]
    except (sp.SympifyError, SyntaxError, TypeError, ValueError, NotImplementedError) as exc:
        checks["shape"] = {
            "pass": False,
            "detail": f"sympify/ring failed during invariant prep: {exc}",
        }
        for k in (
            "ideal_containment_input_to_candidate",
            "ideal_containment_candidate_to_input",
            "s_pair_reduces_to_zero",
        ):
            checks[k] = {"pass": False, "detail": "skipped: parse failed"}
        checks["tag_matches"] = {"pass": True, "detail": "n/a for kind=ok"}
        return _aggregate(checks, t0)

    input_nonzero = [p for p in input_ring if p]
    cand_nonzero = [p for p in cand_ring if p]

    # Two empty-basis edge cases:
    #   input is (0) and candidate is []  → both invariants vacuously pass.
    #   input is non-zero and candidate is [] → candidate is wrong.
    if not cand_nonzero:
        if not input_nonzero:
            checks["ideal_containment_input_to_candidate"] = {
                "pass": True, "detail": "vacuous: both ideals are (0)"}
            checks["ideal_containment_candidate_to_input"] = {
                "pass": True, "detail": "vacuous: both ideals are (0)"}
            checks["s_pair_reduces_to_zero"] = {
                "pass": True, "detail": "vacuous: candidate is empty"}
        else:
            checks["ideal_containment_input_to_candidate"] = {
                "pass": False,
                "detail": "candidate basis is empty but input ideal is non-zero",
            }
            checks["ideal_containment_candidate_to_input"] = {
                "pass": True, "detail": "vacuous: candidate is empty"}
            checks["s_pair_reduces_to_zero"] = {
                "pass": True, "detail": "vacuous: candidate is empty"}
        checks["tag_matches"] = {"pass": True, "detail": "n/a for kind=ok"}
        return _aggregate(checks, t0)

    # Invariant 2: every input polynomial reduces to 0 mod candidate.
    checks["ideal_containment_input_to_candidate"] = _check_input_in_cand(
        input_nonzero, cand_nonzero, R)

    # Invariant 3: every candidate polynomial reduces to 0 mod a GB of input.
    checks["ideal_containment_candidate_to_input"] = _check_cand_in_input(
        cand_nonzero, input_nonzero, R)

    # Invariant 4: every S-pair (or sample) reduces to 0 mod candidate.
    checks["s_pair_reduces_to_zero"] = _check_s_pairs(
        cand_nonzero, R, case_id)

    checks["tag_matches"] = {"pass": True, "detail": "n/a for kind=ok"}
    return _aggregate(checks, t0)


def _aggregate(checks: Dict[str, Dict[str, Any]], t0: float) -> Dict[str, Any]:
    failed = [k for k, v in checks.items() if not v["pass"]]
    return {
        "pass": len(failed) == 0,
        "reason": "all invariants hold" if not failed else f"failed: {', '.join(failed)}",
        "checks": checks,
        "wall_clock_seconds": round(time.time() - t0, 4),
    }


# ---------------------------------------------------------------------
# Individual checks
# ---------------------------------------------------------------------


def _check_shape_ok(inp: Dict, cand: Dict) -> Dict[str, Any]:
    """Static structural validation for happy-path candidates.

    The check ensures every downstream invariant has parsable inputs;
    a structural failure here short-circuits the rest with a 'skipped'.
    """
    if cand.get("kind") != "ok":
        return {"pass": False, "detail": f"candidate.kind={cand.get('kind')!r}, expected 'ok'"}
    if not isinstance(cand.get("basis"), list):
        return {"pass": False, "detail": "candidate.basis is not a list"}
    if cand.get("order") not in ("lex", "degrevlex"):
        return {"pass": False,
                "detail": f"candidate.order={cand.get('order')!r} not in {{lex, degrevlex}}"}
    if cand["order"] != inp["order"]:
        return {"pass": False,
                "detail": f"candidate.order={cand['order']!r} differs from input.order={inp['order']!r}"}
    if cand.get("vars") != inp.get("vars"):
        return {"pass": False, "detail": "candidate.vars does not match input.vars"}

    # Each basis entry must be a string parsable as a SymPy expression in
    # the declared variables.
    sym_locals = {v: sp.Symbol(v) for v in inp["vars"]}
    for i, b in enumerate(cand["basis"]):
        if not isinstance(b, str):
            return {"pass": False, "detail": f"basis[{i}] is not a string"}
        try:
            expr = sp.sympify(b, locals=sym_locals)
        except (sp.SympifyError, SyntaxError, TypeError) as exc:
            return {"pass": False, "detail": f"basis[{i}]={b!r} fails to sympify: {exc}"}
        # Must be a polynomial in the declared vars (no foreign symbols, no
        # transcendental heads). A canonical GB element from a polynomial
        # input is itself a polynomial — by closure of the polynomial ring
        # under the GB construction (CLO Ch.2 §5).
        free = expr.free_symbols
        foreign = free - set(sym_locals.values())
        if foreign:
            return {
                "pass": False,
                "detail": f"basis[{i}]={b!r} mentions foreign symbols: {sorted(str(s) for s in foreign)}",
            }
    return {"pass": True, "detail": f"|basis|={len(cand['basis'])}, order={cand['order']!r}"}


def _check_shape_tagged(cand: Dict) -> Dict[str, Any]:
    tag = cand.get("tag")
    if not isinstance(tag, str):
        return {"pass": False, "detail": "candidate.tag is not a string"}
    if not tag.startswith("groebner-basis/"):
        return {"pass": False, "detail": f"candidate.tag={tag!r} not in groebner-basis/ namespace"}
    if tag not in VALID_REFUSAL_CLASSES:
        return {"pass": False, "detail": f"candidate.tag={tag!r} not a declared refusal class"}
    payload = cand.get("payload", {})
    if not isinstance(payload, dict):
        return {"pass": False, "detail": "candidate.payload is not a record"}
    return {"pass": True, "detail": f"tag={tag!r}"}


def _check_tag_matches(cand: Dict, expected: Dict) -> Dict[str, Any]:
    """Exact tag match against expected.tag (when supplied)."""
    cand_tag = cand.get("tag")
    expected_tag = expected.get("tag") if isinstance(expected, dict) else None
    if not expected_tag:
        return {"pass": True, "detail": f"refused with tag={cand_tag!r} (no expected tag pinned)"}
    if cand_tag != expected_tag:
        return {
            "pass": False,
            "detail": f"candidate.tag={cand_tag!r} != expected.tag={expected_tag!r}",
        }
    return {"pass": True, "detail": f"tag={cand_tag!r} matches expected"}


def _check_input_in_cand(
    input_polys: List[Any],
    cand_polys: List[Any],
    R: Any,
) -> Dict[str, Any]:
    """Every input polynomial reduces to 0 mod candidate basis.

    Uses sympy.polys.rings PolyElement.div, which performs multivariate
    polynomial division under the ring's stored monomial order.
    """
    misses: List[str] = []
    for i, f in enumerate(input_polys):
        try:
            _q, r = f.div(cand_polys)
        except Exception as exc:  # noqa: BLE001
            misses.append(f"input[{i}] reduction errored: {exc}")
            continue
        if r:
            misses.append(
                f"input[{i}]={f.as_expr()} reduces to non-zero {r.as_expr()}"
            )
    if misses:
        return {"pass": False,
                "detail": "; ".join(misses[:3]) + (f" (+{len(misses)-3} more)" if len(misses) > 3 else "")}
    return {"pass": True,
            "detail": f"every input polynomial ({len(input_polys)}) ∈ ⟨candidate⟩"}


def _check_cand_in_input(
    cand_polys: List[Any],
    input_polys: List[Any],
    R: Any,
) -> Dict[str, Any]:
    """Every candidate polynomial reduces to 0 mod GB(input).

    First compute a reference GB of the input ring elements. SymPy's
    `groebner` accepts ring polynomials and returns a `GroebnerBasis`
    iterable of ring polynomials.
    """
    if not input_polys:
        return {"pass": False,
                "detail": "input ideal is (0) but candidate is non-empty"}
    try:
        # sp.groebner via top-level expressions, then convert.
        as_exprs = [p.as_expr() for p in input_polys]
        sym_objs = list(R.symbols)  # already SymPy Symbol objects
        sympy_order = R.order.alias if hasattr(R.order, "alias") else str(R.order)
        ref_gb = list(sp.groebner(as_exprs, *sym_objs, order=sympy_order))
        ref_gb_ring = [R.from_expr(g) for g in ref_gb]
    except Exception as exc:  # noqa: BLE001
        return {"pass": False,
                "detail": f"reference GB computation errored: {exc}"}
    misses: List[str] = []
    for i, g in enumerate(cand_polys):
        try:
            _q, r = g.div(ref_gb_ring)
        except Exception as exc:  # noqa: BLE001
            misses.append(f"candidate[{i}] reduction errored: {exc}")
            continue
        if r:
            misses.append(
                f"candidate[{i}]={g.as_expr()} reduces to non-zero {r.as_expr()}"
            )
    if misses:
        return {"pass": False,
                "detail": "; ".join(misses[:3]) + (f" (+{len(misses)-3} more)" if len(misses) > 3 else "")}
    return {"pass": True,
            "detail": f"every candidate polynomial ({len(cand_polys)}) ∈ ⟨input⟩"}


def _ring_lm_lc(p: Any) -> Tuple[Tuple[int, ...], Any]:
    """Leading monomial exponent vector and leading coefficient of a
    PolyElement under the ring's stored order.

    sympy.polys.rings PolyElement uses a sparse monomial dict; the
    leading monomial under the ring's order is at `.LM` (ExpoVector) and
    the LC at `.LC`.
    """
    lm = p.LM
    lc = p.LC
    return tuple(lm), lc


def _s_polynomial_ring(
    f: Any,
    g: Any,
    R: Any,
) -> Any:
    """Compute S(f, g) in the ring's PolyElement form.

    S(f, g) = (lcm/LM(f))·f / LC(f) − (lcm/LM(g))·g / LC(g)

    where lcm is the monomial LCM of the leading monomials.
    CLO Ch.2 §6 Definition 4 p.84.
    """
    f_exp, f_lc = _ring_lm_lc(f)
    g_exp, g_lc = _ring_lm_lc(g)
    lcm_exp = tuple(max(a, b) for a, b in zip(f_exp, g_exp))
    f_quot_exp = tuple(lcm_exp[i] - f_exp[i] for i in range(len(lcm_exp)))
    g_quot_exp = tuple(lcm_exp[i] - g_exp[i] for i in range(len(lcm_exp)))

    # Build f_quot and g_quot as ring monomials (1·monomial), divided by
    # the corresponding leading coefficients to monicise the contribution.
    f_quot = R.term_new(f_quot_exp, R.domain.one / f_lc)
    g_quot = R.term_new(g_quot_exp, R.domain.one / g_lc)

    return f_quot * f - g_quot * g


def _check_s_pairs(
    cand_polys: List[Any],
    R: Any,
    case_id: str,
) -> Dict[str, Any]:
    """Every S-pair (or sample) reduces to 0 mod candidate."""
    n = len(cand_polys)
    if n < 2:
        return {"pass": True,
                "detail": f"trivially: |basis|={n} < 2 (no pairs to check)"}

    all_pairs = [(i, j) for i in range(n) for j in range(i + 1, n)]
    if n <= LARGE_BASIS_THRESHOLD:
        pairs = all_pairs
        regime = f"all {len(all_pairs)} pairs"
    else:
        seed = int(hashlib.sha256((case_id or "no-id").encode()).hexdigest()[:8], 16)
        rng = random.Random(seed)
        sample_size = min(SAMPLE_PAIR_COUNT, len(all_pairs))
        pairs = rng.sample(all_pairs, sample_size)
        regime = f"sample of {sample_size}/{len(all_pairs)} pairs (seeded RNG, case-id keyed)"

    bad: List[str] = []
    for (i, j) in pairs:
        try:
            spoly = _s_polynomial_ring(cand_polys[i], cand_polys[j], R)
            _q, r = spoly.div(cand_polys)
        except Exception as exc:  # noqa: BLE001
            bad.append(f"({i},{j}): {exc}")
            continue
        if r:
            bad.append(f"({i},{j}): S-pair reduces to non-zero {r.as_expr()}")
    if bad:
        return {"pass": False,
                "detail": f"checked {regime}; failures: " +
                          "; ".join(bad[:3]) + (f" (+{len(bad)-3} more)" if len(bad) > 3 else "")}
    return {"pass": True,
            "detail": f"checked {regime}; all reduce to 0 mod candidate"}


# ---------------------------------------------------------------------
# CLI entry point
# ---------------------------------------------------------------------


def main() -> int:
    raw = sys.stdin.read()
    case = json.loads(raw)
    result = verify(case)
    json.dump(result, sys.stdout, indent=2)
    sys.stdout.write("\n")
    return 0 if result["pass"] else 1


if __name__ == "__main__":
    sys.exit(main())
